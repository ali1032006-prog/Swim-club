/** Arabic number agreement for "child": 1 = singular, 2 = dual, 3–10 = plural, 11+ = singular accusative. */
function childCount(n: number, dualForm: "nominative" | "accusative"): string {
  if (n === 1) return "طفل واحد";
  if (n === 2) return dualForm === "nominative" ? "طفلان" : "طفلين";
  if (n <= 10) return `${n} أطفال`;
  return `${n} طفلًا`;
}

